import React from "react";
import { Document, Page, Text, View, StyleSheet, renderToStream } from "@react-pdf/renderer";
import type { Readable } from "stream";

export type RenderSettlementReceiptArgs = {
  receiptId: string;
  sessionId: string;
  tradeId: number;
  bondName?: string | null;
  bondId?: number | null;
  investorEmail?: string | null;
  amount: number;
  paymentReference?: string | null;
  confirmedAtISO: string;
  confirmedByUserId: string;
  notes?: string | null;
};

const styles = StyleSheet.create({
  page: { padding: 28, fontSize: 10, fontFamily: "Helvetica" },
  header: { marginBottom: 16 },
  h1: { fontSize: 16, marginBottom: 6, fontWeight: "bold" },
  sub: { fontSize: 9, color: "#555" },
  section: { marginTop: 10 },
  label: { fontSize: 9, color: "#222", fontWeight: "bold" },
  value: { fontSize: 10, marginBottom: 6 },
  row: { flexDirection: "row", justifyContent: "space-between", gap: 8 },
  box: { borderWidth: 1, borderColor: "#333", padding: 10, marginTop: 12, backgroundColor: "#f9f9f9" },
  footer: { position: "absolute", bottom: 20, left: 28, right: 28, fontSize: 8, color: "#666", textAlign: "center" },
});

function formatUSD(amount: number): string {
  try {
    return new Intl.NumberFormat("en-US", { style: "currency", currency: "USD" }).format(amount);
  } catch {
    return `$${amount.toFixed(2)}`;
  }
}

function SettlementReceiptTemplate(a: RenderSettlementReceiptArgs) {
  return (
    <Document>
      <Page size="LETTER" style={styles.page}>
        <View style={styles.header}>
          <Text style={styles.h1}>Settlement Receipt</Text>
          <Text style={styles.sub}>JACE CRM • Internal Escrow Confirmation</Text>
          <Text style={styles.sub}>Receipt ID: {a.receiptId}</Text>
        </View>

        <View style={styles.box}>
          <Text style={styles.label}>Settlement Summary</Text>
          <View style={{ height: 8 }} />

          <View style={styles.row}>
            <View style={{ flex: 1 }}>
              <Text style={styles.label}>Trade ID</Text>
              <Text style={styles.value}>{a.tradeId}</Text>
            </View>
            <View style={{ flex: 1 }}>
              <Text style={styles.label}>Session ID</Text>
              <Text style={styles.value}>{a.sessionId}</Text>
            </View>
          </View>

          <View style={styles.row}>
            <View style={{ flex: 1 }}>
              <Text style={styles.label}>Bond</Text>
              <Text style={styles.value}>{a.bondName || "Bond Purchase"}{a.bondId ? ` (Bond #${a.bondId})` : ""}</Text>
            </View>
            <View style={{ flex: 1 }}>
              <Text style={styles.label}>Amount</Text>
              <Text style={styles.value}>{formatUSD(a.amount)}</Text>
            </View>
          </View>

          <View style={styles.section}>
            <Text style={styles.label}>Investor Email</Text>
            <Text style={styles.value}>{a.investorEmail || "n/a"}</Text>

            <Text style={styles.label}>Payment Reference</Text>
            <Text style={styles.value}>{a.paymentReference || "n/a"}</Text>

            <Text style={styles.label}>Confirmed At (ISO)</Text>
            <Text style={styles.value}>{a.confirmedAtISO}</Text>

            <Text style={styles.label}>Confirmed By</Text>
            <Text style={styles.value}>{a.confirmedByUserId}</Text>

            {a.notes ? (
              <>
                <Text style={styles.label}>Notes</Text>
                <Text style={styles.value}>{a.notes}</Text>
              </>
            ) : null}
          </View>
        </View>

        <Text style={styles.footer}>
          This receipt indicates internal confirmation of a settlement request. It is not legal or tax advice. • Generated by JACE CRM
        </Text>
      </Page>
    </Document>
  );
}

function streamToBuffer(stream: Readable): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    stream.on("data", (chunk: Buffer) => chunks.push(chunk));
    stream.on("end", () => resolve(Buffer.concat(chunks)));
    stream.on("error", reject);
  });
}

export async function renderSettlementReceiptPdf(args: RenderSettlementReceiptArgs): Promise<Buffer> {
  const pdfStream = await renderToStream(<SettlementReceiptTemplate {...args} />);
  const buffer = await streamToBuffer(pdfStream as unknown as Readable);
  return buffer;
}
